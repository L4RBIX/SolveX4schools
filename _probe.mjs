import { chromium } from 'playwright';
const B = await chromium.launch();
const p = await (await B.newContext({ viewport:{width:1440,height:1000} })).newPage();
p.on('response', r => { if (r.url().includes('/api/auth')) console.log(r.status(), r.url()); });
await p.goto('http://localhost:3000/login',{waitUntil:'domcontentloaded'});
await p.waitForSelector('input[type="password"]',{timeout:60000});
const i=await p.$$('input'); await i[0].fill('aigul'); await i[1].fill('solvex-demo-2026');
await p.getByRole('button',{name:/Кіру|Войти/}).click();
await p.waitForTimeout(9000);
console.log('url after:', p.url());
console.log('body:', (await p.innerText('body')).replace(/\n+/g,' | ').slice(0,300));
await B.close();
