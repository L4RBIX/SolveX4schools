/**
 * The Help Center's articles.
 *
 * Written against what the product actually does, not against what a help
 * centre usually says. Where an answer is "not yet", it says so — a Help Center
 * that describes features the build does not have is worse than a missing page,
 * because a teacher reads it and then tells a class something untrue.
 *
 * Both languages are authored, not machine-translated: the Kazakh is written as
 * Kazakh rather than as a word-for-word trace of the Russian, and technical
 * syntax (`cout`, `cin`, `if`, `int main()`) stays English in both because
 * renaming keywords would teach a language that does not exist.
 *
 * ## The language is read, never typed
 *
 * `YEAR_ONE_LANGUAGE_LABEL` is imported rather than written out. A help centre
 * that says "Python" while the Run button compiles C++ is the single most
 * expensive kind of wrong page here: a parent reads it, repeats it to a head
 * teacher, and the product has to be argued with instead of used.
 *
 * ## What C++ added to this file
 *
 * Two articles that had no Python equivalent — `running-code` and
 * `compile-error`. In Python, Run either printed or raised; there was one step
 * and one kind of failure. In C++ there are two of each: the program is
 * COMPILED and only then RUN, and it can fail at compile time without ever
 * having run. Help text that explains only runtime errors describes a product
 * the learner does not have, and a fourteen-year-old staring at their first
 * missing semicolon is exactly the reader who comes here.
 */

