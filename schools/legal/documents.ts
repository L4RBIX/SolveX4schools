/**
 * The privacy policy and the terms of use.
 *
 * ## Written from the code, not from a template
 *
 * Every claim below was checked against what the application actually does
 * before it was written down. Where the honest answer is "not yet" or "we do
 * not know", it says that. A privacy page that describes retention windows
 * nobody implemented, or claims a compliance regime nobody audited, is worse
 * than no page: a director reads it, believes it, and repeats it to parents.
 *
 * The specific things verified in the source while writing this:
 *
 * - identity is `school_accounts` + `school_sessions`; there is no email field
 *   on an account, and no password reset by mail, because there is no mail
 * - session tokens are stored as sha256, never in the clear (auth/session.ts)
 * - passwords are scrypt with the cost in the record (auth/password.ts)
 * - teacher access is `class_teachers`, not the role (auth/guard.ts)
 * - Nova's context is assembled in `schools/nova/prompt.ts` and contains only
 *   the current block, the learner's own answer and their own recent attempts
 * - the model provider is DeepSeek when configured, and requests leave our
 *   server, never the browser (nova/providers/deepseek.ts)
 * - code execution is not wired to a third party in this build
 *   (`schools/exec` returns a not-configured result)
 * - there is no automated deletion job. Saying "we delete after N months"
 *   would be a claim about a cron that does not exist.
 *
 * Items needing a lawyer's eye are listed in docs/legal/PRIVACY_LEGAL_REVIEW.md.
 * This is a competent draft, not legal advice, and it does not pretend to be.
 */

